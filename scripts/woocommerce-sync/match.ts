export function isBlendName(name: string, slug = ''): boolean {
  const hay = `${name} ${slug}`.toLowerCase();
  if (hay.includes('blend') || hay.includes('|') || hay.includes('+')) return true;
  const hits = COMPOUND_HINTS.filter((token) => hay.includes(token));
  return hits.length >= 2;
}

export function keysFor(name: string, slug = ''): string[] {
  const keys = new Set<string>();
  keys.add(compactKey(slug));
  keys.add(compactKey(name));
  keys.add(compoundKey(name, slug, false));
  keys.add(compoundKey(name, slug, true));
  return [...keys].filter(Boolean);
}

function aliasMatches(compact: string, slugCompact: string, alias: string): boolean {
  if (compact === alias || slugCompact === alias) return true;
  for (const value of [compact, slugCompact]) {
    if (!value.startsWith(alias)) continue;
    if (alias.length >= 8) return true;
    const rest = value.slice(alias.length);
    if (/^\d*(mg|mcg|iu|ml|g)?$/.test(rest)) return true;
  }
  return false;
}

export function matchExisting(name: string, slug: string, usedIds: Set<string>): ExistingRecord | null {
  const wcIsBlend = isBlendName(name, slug);
  const compactName = compactKey(name);
  const slugCompact = compactKey(slug);
  const wcKeys = new Set(keysFor(name, slug));

  const aliasEntries = Object.entries(ALIASES).sort((a, b) => b[0].length - a[0].length);
  for (const [alias, id] of aliasEntries) {
    if (!aliasMatches(compactName, slugCompact, alias) && !wcKeys.has(alias)) continue;
    const rec = EXISTING_CATALOG.find((row) => row.id === id);
    if (!rec || usedIds.has(rec.id) || rec.extraKind === 'nasal' || rec.extraKind === 'equipment') continue;
    if (wcIsBlend && !BLEND_IDS.has(rec.id) && rec.categoryId !== 'cat-reagents') continue;
    if (!wcIsBlend && BLEND_IDS.has(rec.id)) continue;
    return rec;
  }

  let best: { rec: ExistingRecord; score: number } | null = null;
  for (const rec of EXISTING_CATALOG) {
    if (usedIds.has(rec.id)) continue;
    if (rec.extraKind === 'nasal' || rec.extraKind === 'equipment') continue;
    if (wcIsBlend && !BLEND_IDS.has(rec.id)) continue;
    if (!wcIsBlend && BLEND_IDS.has(rec.id)) continue;

    const recKeys = keysFor(rec.name, rec.slug);
    const overlap = recKeys.filter((key) => wcKeys.has(key) && key.length >= 5);
    if (!overlap.length) continue;
    const score = Math.max(...overlap.map((key) => key.length));
    if (!best || score > best.score) best = { rec, score };
  }

  if (best && best.score >= 5) return best.rec;
  return null;
}
