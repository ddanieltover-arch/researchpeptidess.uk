const BLEND_IDS = new Set(
  EXISTING_CATALOG.filter(
    (row) => row.categoryId === 'cat-sequences' && /blend|\+/.test(`${row.name} ${row.slug}`)
  ).map((row) => row.id)
);

export function compactKey(value: string): string {
  return value
    .toLowerCase()
    .replace(/ß/g, 'b')
    .replace(/β/g, 'b')
    .replace(/α/g, 'a')
    .replace(/\+/g, 'plus')
    .replace(/&/g, '')
    .replace(/[^a-z0-9]+/g, '');
}

const FILLER = /\b(reference|standard|analytical|grade|peptide|peptides|lyophilized|vial|acetate|compound|online|buy|uk|research|laboratory|lab)\b/g;

export function compoundKey(name: string, slug = '', keepSize = false): string {
  const source = `${name} ${slug}`.toLowerCase();
  const withoutFiller = source.replace(FILLER, ' ');
  const sized = keepSize
    ? withoutFiller
    : withoutFiller.replace(/\b\d+(?:\.\d+)?\s?(mg|mcg|iu|ml|g|tablets?)\b/g, ' ');
  return compactKey(sized);
}

